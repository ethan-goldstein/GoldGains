// Copies the on-device OCR engine (Tesseract) out of node_modules into public/,
// so the app never fetches code from a CDN at runtime. Folders are versioned so a
// library upgrade busts the service-worker cache.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = (...p: string[]) => join(root, 'node_modules', ...p);
const version = (pkg: string) => (JSON.parse(readFileSync(nm(pkg, 'package.json'), 'utf8')) as { version: string }).version;

const tessVer = version('tesseract.js');
const coreVer = version('tesseract.js-core');
const ocrDir = join(root, 'public', 'ocr', `t${tessVer}-c${coreVer}`);

const copies: [string, string][] = [
  [nm('tesseract.js', 'dist', 'worker.min.js'), join(ocrDir, 'worker.min.js')],
  // LSTM-only builds: the worker picks one by the device's SIMD support
  [nm('tesseract.js-core', 'tesseract-core-lstm.wasm.js'), join(ocrDir, 'tesseract-core-lstm.wasm.js')],
  [nm('tesseract.js-core', 'tesseract-core-simd-lstm.wasm.js'), join(ocrDir, 'tesseract-core-simd-lstm.wasm.js')],
  [nm('tesseract.js-core', 'tesseract-core-relaxedsimd-lstm.wasm.js'), join(ocrDir, 'tesseract-core-relaxedsimd-lstm.wasm.js')],
  [nm('@tesseract.js-data', 'eng', '4.0.0_best_int', 'eng.traineddata.gz'), join(ocrDir, 'eng.traineddata.gz')],
];

if (!existsSync(join(ocrDir, 'eng.traineddata.gz'))) {
  rmSync(join(root, 'public', 'ocr'), { recursive: true, force: true });
}
mkdirSync(ocrDir, { recursive: true });
for (const [from, to] of copies) {
  if (!existsSync(from)) throw new Error(`missing OCR asset: ${from}`);
  if (!existsSync(to)) copyFileSync(from, to);
}

// The app reads this to know where the engine lives.
const out = join(root, 'src', 'scan', 'ocr', 'assets.gen.ts');
const body = `// generated by scripts/copy-ocr-assets.ts — do not edit\nexport const OCR_DIR = 'ocr/t${tessVer}-c${coreVer}/';\n`;
if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body);
}
console.log(`OCR assets ready in public/${`ocr/t${tessVer}-c${coreVer}`}`);
